function buildSuit(suit: Exclude<Suit, null>, templates: MinorTemplate[]): Row[] {
  return templates.map(([number, meanUp, meanRev, kwUp, kwRev]) => {
    const rank = RANK_NAME[number]
    const rankEn = RANK_NAME_EN[number]
    return [
      `${suit}-${String(number).padStart(2, '0')}`,
      number,
      'minor',
      suit,
      `${SUIT_LABEL[suit]} ${rank}`,
      `${rankEn} of ${suit[0].toUpperCase()}${suit.slice(1)}`,
      SUIT_ICON[suit],
      kwUp,
      kwRev,
      meanUp,
      meanRev,
    ] as Row
  })
}

